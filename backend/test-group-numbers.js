'use strict';
const assert = require('assert');
const service = require('./src/api/services/GroupNumberService');
assert.equal(service.normalizePhone('00966 50 123 4567'), '+966501234567');
assert.equal(service.normalizePhone('+966 (50) 123-4567'), '+966501234567');
assert.equal(service.normalizePhone('123'), null);
assert.equal(service.normalizePhone('12345@lid'), null);
assert.deepEqual(service.classify('+966501234567'), { country_code: '966', country_name: 'السعودية', is_saudi: true });
assert.equal(service.classify('+971501234567').country_name, 'الإمارات');
assert.equal(service.classify('+999501234567').is_saudi, false);
console.log('group-number normalization tests: ok');
